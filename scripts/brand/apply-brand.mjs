/**
 * Regenerate every product-identity artifact from `brand/`.
 *
 * `brand/brand.json` and `brand/logo.svg` are the only hand-edited inputs. The
 * script is idempotent and safe to rerun after merging upstream: it rewrites
 * generated assets and replaces the upstream product name wherever it appears
 * in shipped source. LICENSE and THIRD_PARTY_NOTICES.md are never touched.
 */

