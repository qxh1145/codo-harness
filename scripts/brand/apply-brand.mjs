const names = [UPSTREAM_NAME, applied.productName].filter(name => name !== undefined && name !== brand.productName)
const tracked = execFileSync('git', ['ls-files', '-z', '--', 'apps', 'packages', 'scripts/client-build-environment.ts', 'scripts/client-build-environment.client.spec.ts'],
  { cwd: root, encoding: 'utf8', maxBuffer: 1 << 28 }).split('\0').filter(Boolean)
let textFiles = 0
for (const path of tracked) {
  if (excluded.some(pattern => pattern.test(path)) || !existsSync(at(path))) continue
  const before = readFileSync(at(path))
  if (before.includes(0)) continue
  let text = before.toString('utf8')
  for (const name of names) text = text.split(name).join(brand.productName)
  if (text !== before.toString('utf8')) { write(path, text); textFiles += 1 }
}

// Packaging scripts derive installer file names from the same prefix as electron-builder.
const artifactPrefixes = ['deepseek-harness-', applied.artifactName === undefined ? undefined : `${applied.artifactName}-`]
  .filter(prefix => prefix !== undefined && prefix !== `${brand.artifactName}-`)
const swapPrefixes = text => artifactPrefixes.reduce((value, prefix) => value.split(prefix).join(`${brand.artifactName}-`), text)
for (const path of tracked.filter(item => /^apps\/desktop\/scripts\/[^/]+\.(ts|mjs|mts)$/.test(item))) {
  const before = readFileSync(at(path), 'utf8')
  const after = swapPrefixes(before)
  if (after !== before) write(path, after)
}

