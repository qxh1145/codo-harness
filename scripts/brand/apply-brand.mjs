/** Inner SVG markup placing the logo inside a square of `edge` units at (`x`, `y`). */
function placedLogo(x, y, edge, fill) {
  const scale = edge / Math.max(width, height)
  const dx = x + (edge - width * scale) / 2
  const dy = y + (edge - height * scale) / 2
  return `<g transform="translate(${dx} ${dy}) scale(${scale})"><path d="${logoPath}" fill="${fill}" fill-rule="evenodd"/></g>`
}

